"""E4, pre-registered sensitivity: every decision quantity without the later member of each nested pair
(F-L39, F-H39, F-H30) and without the two questions closest to E3a (F-H36, F-H37).

The frozen analysis (experiments/E1/analyze.py --rules e4) is run unchanged on a copy of the main run whose
attempts.jsonl leaves those questions out (the attempt folders are linked, not copied, so the certificates the
second-opinion rule reads are the same files). Written 2026-11-07 before any E4 result was read.

    taskset -c 4,5 .venv/bin/python experiments/E4/sensitivity.py --out docs/experiments/E4/sensitivity.md
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
RUNS = Path(os.environ.get("DSH_E4_RUNS", ROOT / "experiments/E4/runs"))
SUBSETS = {"main": [], "no_nested": ["F-L39", "F-H39", "F-H30"], "no_close_to_E3a": ["F-H36", "F-H37"]}
ARGS = ["--rules", "e4", "--answer-form", str(ROOT / "experiments/E4/questions/answer_form.json"),
        "--semantic", str(ROOT / "experiments/E4/context/semantic_model.yaml")]


def run_subset(name: str, drop: list[str]) -> dict:
    if not drop:
        return json.loads((RUNS / "main/analysis.json").read_text())
    root = RUNS / f"sens_{name}"
    if root.exists():
        shutil.rmtree(root)
    (root / "main").mkdir(parents=True)
    (root / "main/attempts").symlink_to(RUNS / "main/attempts")
    for f in ("DATA_CATALOG.md",) + tuple(p.name for p in (RUNS / "main").glob("labels*")):
        shutil.copy(RUNS / "main" / f, root / "main" / f)
    kept = [ln for ln in (RUNS / "main/attempts.jsonl").read_text().splitlines()
            if json.loads(ln)["qid"] not in drop]
    (root / "main/attempts.jsonl").write_text("\n".join(kept) + "\n")
    subprocess.run([sys.executable, str(ROOT / "experiments/E1/analyze.py"), "--runs-root", str(root), "--run", "main",
                    *ARGS], check=True, stdout=subprocess.DEVNULL)
    return json.loads((root / "main/analysis.json").read_text())


def pct(x) -> str:
    return "—" if x is None else f"{100 * x:.1f}%"


def ci(c) -> str:
    return "—" if not c else f"[{100 * c[0]:+.1f}, {100 * c[1]:+.1f}]"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args()
    res = {name: run_subset(name, drop) for name, drop in SUBSETS.items()}
    L = ["# E4 sensitivity (pre-registered; generated by experiments/E4/sensitivity.py)", "",
         "| subset | questions left out | M1(N) | M1(H) | H − N [95%] | M2(H) | R1 | R2 | R3 | "
         "M1(H+t2n) − M1(N+pair) [95%] | M2 t2n / pair | runs per attempt | R4 |",
         "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for name, d in res.items():
        dec = d["decision"]
        r1, r4 = dec["R1"], dec["R4"]
        L.append(f"| {name} | {', '.join(SUBSETS[name]) or '—'} | {pct(r1['M1_N'])} | {pct(r1['M1_H'])} | "
                 f"{ci(r1['diff_ci95'])} | {pct(r1['M2_H'])} | {'met' if r1['met'] else 'not met'} | "
                 f"{'met' if dec['R2']['met'] else 'not met'} | {'met' if dec['R3']['met'] else 'not met'} | "
                 f"{ci(r4.get('diff_M1_ci95'))} | {pct(r4.get('M2_t2n'))} / {pct(r4.get('M2_pair'))} | "
                 f"{r4.get('runs_per_attempt_t2n') or '—'} | {'met' if r4.get('met') else 'not met'} |")
    a.out.write_text("\n".join(L) + "\n")
    a.out.with_suffix(".json").write_text(json.dumps({k: v["decision"] for k, v in res.items()}, indent=1, default=str))
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
