"""E1b, exploratory: why the harness held correct answers (M2) and passed wrong ones (M1).

For every harness-arm attempt (H, H1) that was correct but not delivered, or wrong but delivered, read
the attempt's own registry (harness_ws/registry): the last answer certificate, its gate verdict and the
reason the reconcile check gave. Reasons are grouped after removing the specifics (column lists,
numbers, months), so the table shows the kinds of hold, not single cases. Not a decision rule.

    .venv/bin/python experiments/E1b/hold_reasons.py --run main
"""
from __future__ import annotations

import argparse
from collections import Counter
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))
from dsharness.common import read_jsonl  # noqa: E402

GENERIC = [(re.compile(r"\[[^\]]*\]"), "[…]"), (re.compile(r"'[^']*'"), "'…'"),
           (re.compile(r"\d{4}-\d{2}(-\d{2})?"), "<month>"), (re.compile(r"-?\d+(\.\d+)?(e-?\d+)?"), "<n>")]


def generic(reason: str) -> str:
    for pat, rep in GENERIC:
        reason = pat.sub(rep, reason)
    return reason[:160]


def latest(records):
    keep = {}
    for r in records:
        if r.get("status") not in ("RETRY", "SKIPPED"):
            keep[(r["agent"], r["arm"], r["qid"], r["rep"])] = r
    return list(keep.values())


def _why(m: dict) -> str:
    g = m.get("governed") or {}
    if m.get("reason") or g.get("reason"):
        return m.get("reason") or g.get("reason")
    if m.get("contradictions"):           # declared metric_call reconciles but does not answer the question as asked
        return "metric_call contradicts the question: " + "; ".join(m["contradictions"])
    for d in (m, g):
        if d.get("n_missing_keys") or d.get("n_extra_keys") or d.get("n_mismatches"):
            return (f"{d.get('n_missing_keys', 0)} keys missing, {d.get('n_extra_keys', 0)} extra, "
                    f"{d.get('n_mismatches', 0)} values differ (of {d.get('n_expected')} governed rows)")
    return "(no reason recorded)"


def last_check(attempt_dir: Path) -> dict:
    """Tier, verdict and per-check outcome/reason of the attempt's last answer certificate."""
    reg = Path(attempt_dir) / "harness_ws" / "registry"
    certs = read_jsonl(reg / "answer_certificates.jsonl") if (reg / "answer_certificates.jsonl").exists() else []
    if not certs:
        return {"tier": None, "fails": ["no answer certificate (never submitted)"]}
    c = certs[-1]
    ev = {e["evidence_id"]: e for e in read_jsonl(reg / "evidence.jsonl")}
    fails = []
    for ch in c.get("checks", []):
        if ch.get("outcome") in ("PASS", "NOT_RUN", "NOT_APPLICABLE"):
            continue
        why = _why(ev.get(ch.get("evidence_id"), {}).get("metrics") or {})
        fails.append(f"{ch['check_id']} {ch['outcome']}: {generic(str(why))}")
    return {"tier": c.get("tier") or (c.get("trust") or {}).get("tier"), "fails": fails or ["all checks PASS"],
            "n_certs": len(certs)}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", required=True)
    ap.add_argument("--runs-root", type=Path, default=ROOT / "experiments/E1b/runs")
    ap.add_argument("--answer-form", type=Path, default=ROOT / "experiments/E1b/questions/answer_form.json")
    ap.add_argument("--out", type=Path, default=None, help="markdown file (default: print)")
    a = ap.parse_args()
    run = a.runs_root / a.run
    form = {}
    for r in json.loads(a.answer_form.read_text()):
        form[r["qid"]] = r["form"] if r["form"] == "DIRECT" else ("DERIVED-none" if r.get("metric") is None
                                                                 else "DERIVED-step")
    recs = [r for r in latest(read_jsonl(run / "attempts.jsonl")) if r["arm"] in ("H", "H1")]
    exp = a.runs_root.resolve().parent.name          # experiments/<E1b|E3a>/runs -> the experiment's name
    L = [f"# {exp} hold and pass reasons (exploratory, generated by hold_reasons.py)", ""]
    for title, pick in (("Correct but held (M2)", lambda r: r.get("correct") and not r.get("delivered")),
                        ("Wrong but delivered (M1)", lambda r: not r.get("correct") and r.get("delivered"))):
        for arm in ("H", "H1"):
            sel = sorted((r for r in recs if r["arm"] == arm and pick(r)), key=lambda r: (r["qid"], r["agent"], r["rep"]))
            cnt = Counter()
            rows = []
            for r in sel:
                lc = last_check(Path(r["attempt_dir"]) if Path(r["attempt_dir"]).is_absolute()
                                else ROOT / r["attempt_dir"])
                h = r.get("harness") or {}
                # the census reason (final rows are no submission's, or no submission) is the cause only when the
                # submission it fell back to would itself have passed; else the certificate's own failures are
                if h.get("reason") and h.get("tier") in (None, "VERIFIED") and h.get("verdict") in (None, "ALLOW", "NO_SUBMISSION"):
                    lc["fails"] = [f"census: {h['reason']}"]
                for f in lc["fails"]:
                    cnt[(form.get(r["qid"], "?"), f)] += 1
                rows.append(f"| {r['qid']} | {form.get(r['qid'], '?')} | {r['agent']} | {r['rep']} | "
                            f"{(r.get('harness') or {}).get('tier')} | {'; '.join(lc['fails'])} |")
            L += [f"## {title}, arm {arm}: {len(sel)} attempts", "", "| form | check and reason | attempts |",
                  "|---|---|---|"]
            L += [f"| {f} | {why} | {n} |" for (f, why), n in sorted(cnt.items(), key=lambda t: (-t[1], t[0]))]
            L += ["", "<details><summary>attempts</summary>", "", "| qid | form | agent | rep | tier | reasons |",
                  "|---|---|---|---|---|---|", *rows, "", "</details>", ""]
    text = "\n".join(L) + "\n"
    if a.out:
        a.out.write_text(text, encoding="utf-8")
        print(f"-> {a.out}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
